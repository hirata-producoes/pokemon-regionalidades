static bool32 IsFieldMoveAlwaysAvailable(void)
{
    // World exploration is never licensed by badges or story flags. The
    // party/menu and interaction scripts still require a non-Egg Pokemon that
    // actually knows the move, plus a valid target or destination.
    return TRUE;
}

